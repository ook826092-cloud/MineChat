package cn.mine.minestars.data.db.entity

import androidx.room.ColumnInfo
import androidx.room.Entity
import androidx.room.PrimaryKey

@Entity(tableName = "assistants")
data class AssistantEntity(
    @PrimaryKey val id: String,
    val name: String,
    @ColumnInfo(name = "chat_model_id") val chatModelId: String?,
    @ColumnInfo(name = "character_card_id") val characterCardId: String?,
    @ColumnInfo(name = "knowledge_base_id") val knowledgeBaseId: String?,
    @ColumnInfo(name = "preset_id") val presetId: String?,
    @ColumnInfo(name = "user_persona_id") val userPersonaId: String?,
    val avatar: String,
    @ColumnInfo(name = "use_assistant_avatar") val useAssistantAvatar: Boolean,
    @ColumnInfo(name = "enable_memory") val enableMemory: Boolean,
    @ColumnInfo(name = "use_global_memory") val useGlobalMemory: Boolean,
    @ColumnInfo(name = "enable_recent_chats_reference") val enableRecentChatsReference: Boolean,
    @ColumnInfo(name = "message_template") val messageTemplate: String,
    @ColumnInfo(name = "quick_message_ids") val quickMessageIds: String,
    @ColumnInfo(name = "regex_group_ids") val regexGroupIds: String?,
    @ColumnInfo(name = "world_book_ids") val worldBookIds: String?,
    @ColumnInfo(name = "world_book_json") val worldBookJson: String?,
    @ColumnInfo(name = "regex_scripts_json") val regexScriptsJson: String?,
    @ColumnInfo(name = "custom_headers") val customHeaders: String?,
    @ColumnInfo(name = "custom_bodies") val customBodies: String?,
    @ColumnInfo(name = "local_tools") val localTools: String,
    val background: String?,
    @ColumnInfo(name = "background_opacity") val backgroundOpacity: Float,
    @ColumnInfo(name = "enabled_skills") val enabledSkills: String,
    @ColumnInfo(name = "enable_time_reminder") val enableTimeReminder: Boolean,
    @ColumnInfo(name = "allow_conversation_system_prompt") val allowConversationSystemPrompt: Boolean,
    @ColumnInfo(name = "interleaved_thinking") val interleavedThinking: Boolean,
    @ColumnInfo(name = "context_message_count") val contextMessageCount: Int,
    @ColumnInfo(name = "char_name") val charName: String,
    val description: String,
    val personality: String,
    val scenario: String,
    @ColumnInfo(name = "first_message") val firstMessage: String,
    @ColumnInfo(name = "mes_examples") val mesExamples: String,
    @ColumnInfo(name = "main_prompt_override") val mainPromptOverride: String,
    @ColumnInfo(name = "post_history_instructions") val postHistoryInstructions: String,
    @ColumnInfo(name = "creator_notes") val creatorNotes: String,
    @ColumnInfo(name = "alternate_greetings") val alternateGreetings: String,
    @ColumnInfo(name = "group_only_greetings") val groupOnlyGreetings: String,
    val nickname: String,
    @ColumnInfo(name = "card_tags") val cardTags: String,
    val creator: String,
    @ColumnInfo(name = "character_version") val characterVersion: String,
    val source: String,
    @ColumnInfo(name = "display_order") val displayOrder: Int,
    @ColumnInfo(name = "created_at") val createdAt: Long,
    @ColumnInfo(name = "updated_at") val updatedAt: Long,
    @ColumnInfo(name = "workspace_id") val workspaceId: String? = null,
    @ColumnInfo(name = "mcp_server_ids") val mcpServerIds: String = "[]",
)
