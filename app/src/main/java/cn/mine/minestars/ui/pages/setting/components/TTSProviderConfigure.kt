/**
 * 使用 DropdownMenu 而非 ExposedDropdownMenuBox 的下拉选择字段。
 * ExposedDropdownMenuBox 在键盘弹出时可能因 coerceIn 位置计算崩溃，
 * 使用普通的 Box + DropdownMenu 避免此问题。
 */
@Composable
private fun <T> DropdownSelectField(
    value: String,
    onValueChange: (String) -> Unit,
    options: List<T>,
    optionLabel: (T) -> String,
    onOptionSelected: (T) -> Unit,
    modifier: Modifier = Modifier,
    placeholder: @Composable () -> Unit = {},
    readOnly: Boolean = false,
) {
    var expanded by remember { mutableStateOf(false) }
    Box(modifier = modifier) {
        OutlinedTextField(
            value = value,
            onValueChange = if (readOnly) {{ }} else onValueChange,
            readOnly = readOnly,
            modifier = Modifier.fillMaxWidth(),
            placeholder = placeholder,
            trailingIcon = {
                IconButton(onClick = { expanded = true }) {
                    Icon(
                        imageVector = if (expanded) HugeIcons.ArrowUp01 else HugeIcons.ArrowDown01,
                        contentDescription = "Expand"
                    )
                }
            }
        )
        DropdownMenu(
            expanded = expanded,
            onDismissRequest = { expanded = false }
        ) {
            options.forEach { option ->
                DropdownMenuItem(
                    text = { Text(optionLabel(option)) },
                    onClick = {
                        expanded = false
                        onOptionSelected(option)
                    }
                )
            }
        }
    }
}
